-- ── Triggers updated_at ────────────────────────────────────────────────────

-- Los avisos nuevos arrancan como borrador solo si no se indica estado
-- (reemplaza al antiguo DEFAULT con subconsulta, que Postgres no soporta).
create or replace function default_borrador_status()
returns trigger
language plpgsql
as $$
begin
  if new.status_id is null then
    new.status_id = (select id from property_statuses where code = 'borrador');
  end if;
  return new;
end;
$$;

drop trigger if exists trg_auctions_default_status on auctions;
create trigger trg_auctions_default_status
  before insert on auctions
  for each row execute function default_borrador_status();

drop trigger if exists trg_machinery_default_status on machinery;
create trigger trg_machinery_default_status
  before insert on machinery
  for each row execute function default_borrador_status();

drop trigger if exists trg_auctions_updated_at on auctions;
create trigger trg_auctions_updated_at
  before update on auctions
  for each row execute function set_updated_at();

drop trigger if exists trg_machinery_updated_at on machinery;
create trigger trg_machinery_updated_at
  before update on machinery
  for each row execute function set_updated_at();

