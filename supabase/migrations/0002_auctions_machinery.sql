-- ── Remates ────────────────────────────────────────────────────────────────

create table if not exists auctions (
  id               uuid primary key default gen_random_uuid(),
  slug             text unique not null,
  title            text not null check (char_length(title) between 1 and 200),
  status_id        smallint not null
                     references property_statuses (id),
  event_status     text not null default 'proximo'
                     check (event_status in ('proximo', 'realizado', 'cancelado')),
  scheduled_at     timestamptz not null,
  location         text check (location is null or char_length(location) <= 200),
  auctioneer       text check (auctioneer is null or char_length(auctioneer) <= 120),
  minimum_bid      numeric(14, 2) check (minimum_bid is null or minimum_bid >= 0),
  currency         text not null default 'USD',
  description      text,
  is_featured      boolean not null default false,
  main_image_path  text,
  main_image_url   text,
  published_at     timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create table if not exists auction_lots (
  id          uuid primary key default gen_random_uuid(),
  auction_id  uuid not null references auctions (id) on delete cascade,
  lot_number  integer not null check (lot_number >= 1),
  title       text check (title is null or char_length(title) <= 200),
  description text,
  minimum_bid numeric(14, 2) check (minimum_bid is null or minimum_bid >= 0),
  sort_order  smallint not null default 0,
  unique (auction_id, lot_number)
);

create table if not exists auction_images (
  id            uuid primary key default gen_random_uuid(),
  auction_id    uuid not null references auctions (id) on delete cascade,
  storage_path  text not null,
  url           text,
  alt_text      text,
  sort_order    smallint not null default 0,
  is_main       boolean not null default false,
  created_at    timestamptz not null default now()
);

create unique index if not exists uq_auction_images_main
  on auction_images (auction_id) where is_main;

-- ── Maquinaria ─────────────────────────────────────────────────────────────

create table if not exists machinery (
  id               uuid primary key default gen_random_uuid(),
  slug             text unique not null,
  title            text not null check (char_length(title) between 1 and 200),
  category_id      smallint not null references machinery_categories (id),
  brand            text check (brand is null or char_length(brand) <= 80),
  model            text check (model is null or char_length(model) <= 80),
  year             smallint check (year is null or year between 1900 and 2100),
  hours_used       integer check (hours_used is null or hours_used >= 0),
  price            numeric(14, 2) check (price is null or price >= 0),
  currency         text not null default 'USD',
  department       text not null,
  locality         text,
  description      text,
  status_id        smallint not null
                     references property_statuses (id),
  is_featured      boolean not null default false,
  main_image_path  text,
  main_image_url   text,
  published_at     timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create table if not exists machinery_images (
  id            uuid primary key default gen_random_uuid(),
  machinery_id  uuid not null references machinery (id) on delete cascade,
  storage_path  text not null,
  url           text,
  alt_text      text,
  sort_order    smallint not null default 0,
  is_main       boolean not null default false,
  created_at    timestamptz not null default now()
);

create unique index if not exists uq_machinery_images_main
  on machinery_images (machinery_id) where is_main;

-- ── Inquiries: sujeto polimórfico ──────────────────────────────────────────

alter table inquiries
  add column if not exists auction_id   uuid references auctions (id) on delete set null,
  add column if not exists machinery_id uuid references machinery (id) on delete set null;

-- A lo sumo uno de los tres sujetos queda completo.
alter table inquiries
  drop constraint if exists inquiries_single_subject;
alter table inquiries
  add constraint inquiries_single_subject
  check (num_nonnulls(property_id, auction_id, machinery_id) <= 1);

