-- Categorías: lectura pública.
drop policy if exists public_read_machinery_categories on machinery_categories;
create policy public_read_machinery_categories on machinery_categories
  for select using (true);
drop policy if exists admin_all_machinery_categories on machinery_categories;
create policy admin_all_machinery_categories on machinery_categories
  for all using (is_admin()) with check (is_admin());

-- Remates: público solo publicados; admin todo.
drop policy if exists public_read_published_auctions on auctions;
create policy public_read_published_auctions on auctions
  for select using (
    status_id = (select id from property_statuses where code = 'publicado')
    or is_admin()
  );
drop policy if exists admin_write_auctions on auctions;
create policy admin_write_auctions on auctions
  for all using (is_admin()) with check (is_admin());

-- Lotes: visibles si el remate es visible.
drop policy if exists public_read_visible_lots on auction_lots;
create policy public_read_visible_lots on auction_lots
  for select using (
    exists (
      select 1 from auctions a
      where a.id = auction_lots.auction_id
        and (
          a.status_id = (select id from property_statuses where code = 'publicado')
          or is_admin()
        )
    )
  );
drop policy if exists admin_write_lots on auction_lots;
create policy admin_write_lots on auction_lots
  for all using (is_admin()) with check (is_admin());

